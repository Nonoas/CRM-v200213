create table DICT
(
    D_KEY     VARCHAR not null,
    D_COMMENT VARCHAR,
    D_VAL     VARCHAR not null,
    D_NAME    VARCHAR,
    constraint DICT_PK
        primary key (D_KEY, D_VAL)
);

comment on table DICT is '数据字典';

create table GOODS_INFO
(
    ID             VARCHAR not null
        primary key,
    NAME           VARCHAR,
    SELL_PRICE     DOUBLE,
    PURCHASE_PRICE DOUBLE,
    QUANTITY       DOUBLE,
    MIN_DISCOUNT   DOUBLE,
    DEDUCTION      DOUBLE,
    DEDUCTION_RATE DOUBLE,
    BASE_UNIT      VARCHAR,
    TYPE           VARCHAR,
    PHOTO          VARCHAR
);

create table GOODS_SNAPSHOT
(
    ID             VARCHAR       not null,
    NAME           VARCHAR,
    SELL_PRICE     DOUBLE,
    PURCHASE_PRICE DOUBLE,
    QUANTITY       DOUBLE,
    MIN_DISCOUNT   DOUBLE,
    DEDUCTION      DOUBLE,
    DEDUCTION_RATE DOUBLE,
    BASE_UNIT      VARCHAR,
    TYPE           VARCHAR,
    PHOTO          VARCHAR,
    GOODS_STATUS   INT default 0 not null,
    SNAP_VERSION   INT default 0 not null,
    constraint GOODS_SNAPSHOT_PK
        primary key (ID, SNAP_VERSION)
);

comment on table GOODS_SNAPSHOT is '商品快照表';

comment on column GOODS_SNAPSHOT.SNAP_VERSION is '快照版本';

create table GOODS_TYPE
(
    GT_ID   VARCHAR not null,
    GT_NAME VARCHAR,
    constraint GOODS_TYPE_PK
        primary key (GT_ID)
);

create table LOGIN_INFO
(
    ID       VARCHAR(20) not null
        primary key,
    NAME     VARCHAR(10) not null,
    PASSWORD VARCHAR,
    ROOT     INTEGER
);

comment on table LOGIN_INFO is '登录信息';

create table MENU_CONDITION
(
    MENU_CODE      VARCHAR    not null,
    ELEMENT_CODE   VARCHAR    not null,
    CONDITION_TYPE VARCHAR(1) not null,
    ELEMENT_NAME   VARCHAR,
    SORT_NO        INT,
    VISIBLE        INT default 1,
    DATA_WIDTH     INT,
    CONTROL_TYPE   VARCHAR,
    constraint MENU_CONDITION_PK
        primary key (MENU_CODE, ELEMENT_CODE, CONDITION_TYPE)
);

create table ORDER_DETAILS
(
    ORDER_ID       VARCHAR(30) not null,
    PRODUCT_ID     VARCHAR(30) not null,
    PRODUCT_AMOUNT INTEGER,
    primary key (ORDER_ID, PRODUCT_ID)
);

create table ORDER_INFO
(
    ORDER_ID      VARCHAR(30) not null,
    USER_ID       VARCHAR(30) not null,
    DATETIME      DATETIME    not null,
    PRICE         REAL        not null,
    TRANSACTOR    TEXT(10)    not null,
    INTEGRAL_COST INTEGER,
    INTEGRAL_GET  INTEGER,
    PAY_MODE      TEXT(10),
    constraint "order_pk"
        primary key (ORDER_ID)
);

create table PACKAGE_CONTENT
(
    PKG_ID       VARCHAR not null,
    GOODS_ID     VARCHAR not null,
    GOODS_AMOUNT INTEGER,
    primary key (PKG_ID, GOODS_ID)
);

create table PACKAGE_INFO
(
    ID            VARCHAR not null
        primary key,
    NAME          VARCHAR,
    INTEGRAL_COST INTEGER,
    MONEY_COST    DOUBLE,
    MIN_DISCOUNT  DOUBLE,
